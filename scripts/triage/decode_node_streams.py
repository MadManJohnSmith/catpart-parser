#!/usr/bin/env python3
"""List-node point streams of the composite stores, decoded (G6, #34).

Byte decode of the scene-graph list nodes' point regions (``04 04 fd
ff`` node records carrying the ``ff ff 02 00 01`` token) under the
stage-3b table law.  Since stage 2c the decode machinery lives in the
shipped ``catpart.geometry.composite`` (the exporter's integration,
fail-closed under the same law); this script is its corpus runner.  No
fitness history is written.

Model (docs/evidence/2026-11-10-node-streams.md, stage-3b table law
dated 2026-11-11):

- Layout (P1t corrected): payload = header + token ``ff ff 02 00 01`` +
  the declared counts + a zero block + the 2-bit per-element table of
  EXACTLY ceil(element_count / 4) bytes (the stage-2c "+1 byte" was
  the count byte miscounted into the table span) + a P1g count of the
  region's f32 words (1 B, ff escapes to u32le) + the region + a
  trailing region (U2).
- Table semantics (U1 solved): 2 bits per element, LSB-first: 0 =
  [x][y][z], 1 = skip (curve entry, U4), 2 = [z], 3 = [y][z]; the
  initial LCP state is the origin (P1i subsumed).  The walk is
  deterministic and consumes exactly the declared write count.
- References (M2b identity, stage 3d): facet/edge references are
  0-based element indices in region order — no sigma search.  The
  stage-2c sigma-era columns of this CSV (the monotone plane-shift
  profiles) are RETIRED 2026-11-11 (stage 3d): the shift was the
  written-index matching artifact, and the loop plane law is measured
  by the stage-3b loop battery (decode_big_form_points.py) over both
  forms.

UPDATED 2026-11-11 (stage 3d): decodes through the identity law; the
committed node-streams-files.csv is the stage-2c historical
measurement and is NOT regenerated by this stage — current rates live
in big-form-points-files.csv (stage 3b) and the A/B exporter CSV.

Outputs docs/evidence/data/node-streams-files.csv (one row per
composite store) and a summary on stdout.  Deterministic: sorted
manifest order; no wall-clock value enters the CSV.

Read-only over the corpus; run with the worktree venv:
  .venv/bin/python -I scripts/triage/decode_node_streams.py
  [--include-sha16 HEX16,...]  restrict to these parts
"""

import argparse
import csv
import mmap
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "manifests" / "corpus-manifest.csv"
OUT_DIR = ROOT / "docs" / "evidence" / "data"

sys.path.insert(0, str(ROOT / "scripts" / "triage"))
sys.path.insert(0, str(ROOT / "src"))

from catpart.geometry import facets, pool, store  # noqa: E402
from catpart.geometry import composite  # noqa: E402
from decode_nested_store import release_of  # noqa: E402

FIELDS = [
    "sha256", "split", "release", "size_bytes", "pool_size",
    "list_node_bytes", "elem_decl", "edge_bound_decl", "node_form",
    "write_count", "region_bytes", "pts_written", "skip_slots",
    "pool_in_list", "pool_coverage", "pool_absorbed", "curve_entries",
    "audit_error",
]


def audit_part(mm, rel):
    """One part: identity-law node audit. Returns the CSV row dict."""
    row = {k: "" for k in FIELDS}
    row["sha256"] = rel["sha256"]
    row["split"] = rel["split"]
    row["release"] = release_of(rel["detected_version"])
    row["size_bytes"] = mm.size()
    d8_outer = int.from_bytes(mm[8:12], "big") if mm.size() >= 12 else 0
    blocks = store.valid_blocks(mm)
    for blk in [b for b, nm in blocks if nm == "CATStdCont"]:
        try:
            span = store.locate_store(mm, blk, blocks, d8_outer)
        except Exception:  # noqa: BLE001 - recorded per part
            continue
        if span is None:
            continue
        lo, hi = span.body_lo, span.body_hi
        try:
            groups, kinds = pool.scan_pool_groups(mm, lo, hi)
        except Exception:  # noqa: BLE001 - recorded per part
            continue
        if not pool.has_composite_space(kinds):
            continue
        poolv = [v for g in groups for v in g.vertices]
        row["pool_size"] = len(poolv)
        hdrs = [m.start() for m in facets.STRIP_RE.finditer(mm, lo, hi)]
        node_hi = hdrs[0] if hdrs else hi
        ln = composite.find_list_node(mm, lo, node_hi)
        if ln is None:
            return row
        payload, c1, c2 = ln
        row["list_node_bytes"] = len(payload)
        row["elem_decl"] = c1
        row["edge_bound_decl"] = c2
        row["node_form"] = "big" if len(payload) > 4096 else "small"
        try:
            points, skips, info = composite.decode_node_points(payload, c1)
        except Exception as exc:  # noqa: BLE001 - recorded per part
            row["audit_error"] = f"{type(exc).__name__}: {exc}"
            return row
        row["write_count"] = info["write_count"]
        row["region_bytes"] = info["region_bytes"]
        row["pts_written"] = len(points)
        row["skip_slots"] = skips
        row["curve_entries"] = skips
        ps = set(poolv)
        hits = len(ps & set(points))
        row["pool_in_list"] = hits
        row["pool_coverage"] = round(hits / len(poolv), 4) if poolv else ""
        row["pool_absorbed"] = hits == len(ps)
        return row
    return row


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--include-sha16", default="")
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    args = ap.parse_args()
    rows_in = [
        r
        for r in csv.DictReader(MANIFEST.open())
        if r["split"] in ("dev", "held-out") and r["kind"] == "part"
    ]
    if args.include_sha16:
        want = {h for h in args.include_sha16.split(",") if h}
        rows_in = [r for r in rows_in if r["sha256"][:16] in want]
    rows_in.sort(key=lambda r: r["sha256"])
    out_rows = []
    for r in rows_in:
        path = ROOT / r["local_path"]
        with path.open("rb") as fh:
            mm = mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ)
            try:
                row = audit_part(mm, r)
            except Exception as exc:  # noqa: BLE001 - recorded per part
                row = {k: "" for k in FIELDS}
                row["sha256"] = r["sha256"]
                row["split"] = r["split"]
                row["audit_error"] = f"{type(exc).__name__}: {exc}"
            finally:
                mm.close()
        out_rows.append(row)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "node-streams-files.csv"
    with out_path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(out_rows)
    print(f"wrote {out_path} ({len(out_rows)} rows)")
    summarize(out_rows)
    return 0


def summarize(rows):
    """Per-claim rates over the audited stores."""
    have = [r for r in rows if r.get("node_form") in ("small", "big")]
    print(f"== identity-law node audit: {len(have)} composite stores with a "
          f"list node of {len(rows)} parts")
    aerr = [r for r in rows if r["audit_error"]]
    print(f"  audit errors: {len(aerr)}")
    if not have:
        return
    for form in ("small", "big"):
        fr = [r for r in have if r["node_form"] == form]
        if not fr:
            continue
        dec = [r for r in fr if str(r["pool_absorbed"]) == "True"]
        walk = [r for r in fr if not r["audit_error"]]
        print(f"  {form}-form: {len(fr)} stores; walk decodes: {len(walk)}; "
              f"pool fully contained: {len(dec)}")
    held = [r for r in have if r["split"] == "held-out"]
    print(f"  held-out rows: {len(held)}")


if __name__ == "__main__":
    sys.exit(main())
