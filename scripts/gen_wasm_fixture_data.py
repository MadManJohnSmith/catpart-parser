#!/usr/bin/env python3
"""Regenerate ``port/tests/fixtures/mod.rs`` — the fixture-byte subset
the wasm-bindgen Node tests decode (Phase 5 spec §7 step 6: CI *runs*
the shipped artifact headlessly on a small fixture subset, canonical
store + corrupted variants).

Why committed Rust source arrays and not committed fixture binaries:
the A2 binary guard (``tests/test_fixturegen.py``) rejects any tracked
file whose first 8 bytes are the ``V5_CFV2`` magic, and the
wasm-bindgen test harness under Node has no filesystem access
(``wasm32-unknown-unknown`` std has no fs), so the bytes cross as
source. The generator is a pure function of ``tests/fixtures_gen.py``
(the SAME generator the fixture-mode Fidelity harness drives), and
``tests/test_wasm_fixture_data.py`` re-runs it and pins the committed
file byte-identical — regenerate, never hand-edit.

Usage::

    python scripts/gen_wasm_fixture_data.py            # write in place
    python scripts/gen_wasm_fixture_data.py --out PATH # write elsewhere

Stdlib-only (the ``publish_fitness.py`` convention for local tools).
"""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO_ROOT / "port" / "tests" / "fixtures" / "mod.rs"

#: The §7 step 6 subset: the canonical store, one corrupted variant per
#: classified class, the composite curve-entry shape (the §2.3 curve
#: exposure at the boundary), and the short-file inspect refusal. Each
#: row: the Rust const name, the fixtures_gen variant (None = the
#: A2 canonical front end without a nested store), a short prose note.
SUBSET: list[tuple[str, str | None, str]] = [
    (
        "GEOMETRY",
        "geometry",
        "the canonical store: 8-vertex pool, 12 triangles, closed "
        "manifold — the export-success row",
    ),
    (
        "BAD_NESTED_MAGIC",
        "geometry-bad-nested-magic",
        "corrupted nested store magic -> missing-geometry-store",
    ),
    (
        "TRUNCATED_POOL",
        "geometry-truncated-pool",
        "pool count field exceeds the walked records -> "
        "malformed-pool-group",
    ),
    (
        "NAN_COORDS",
        "geometry-nan-coords",
        "a NaN pool coordinate -> malformed-pool-vertex",
    ),
    (
        "OUT_OF_RANGE_REFS",
        "geometry-out-of-range-refs",
        "a facet reference past the pool -> undecoded-variant",
    ),
    (
        "COMPOSITE_CURVE_ENTRIES",
        "geometry-composite-law-curve-entries",
        "the composite decode with dropped curve-entry loops: the §2.3 "
        "curve exposure is non-empty at the boundary",
    ),
    (
        "SHORT_FILE",
        "short-file",
        "16 bytes: the inspect seam's crash-class refusal (and the "
        "export seam's store-less missing-geometry-store)",
    ),
]

HEADER = """\
//! GENERATED file — the fixture-byte subset the wasm-bindgen Node
//! tests decode (spec docs/specs/phase5-viewer-spec.md §7 step 6: CI
//! runs the shipped artifact headlessly on a small fixture subset).
//! Regenerated by ``scripts/gen_wasm_fixture_data.py`` from
//! ``tests/fixtures_gen.py`` (the A2 fixture generator the fixture-mode
//! Fidelity harness drives); ``tests/test_wasm_fixture_data.py`` pins
//! this file byte-identical to a fresh regeneration. NEVER hand-edit.
//!
//! Why source arrays and not committed binaries: the A2 binary guard
//! rejects tracked files carrying the ``V5_CFV2`` magic, and the
//! wasm-bindgen harness under Node has no filesystem access (no std
//! fs on wasm32-unknown-unknown) — the bytes cross as source.
//!
//! ``#[rustfmt::skip]`` per const: generated layout, mechanically
//! compared — rustfmt must not reflow the arrays out from under the
//! pin (this is generated data, not the §2.2 decode arithmetic the
//! skip policy guards).
"""


def load_fixtures_gen():
    """Import ``tests/fixtures_gen.py`` by file path (standalone
    module — the ``fidelity_run.py`` loader convention)."""
    path = REPO_ROOT / "tests" / "fixtures_gen.py"
    spec = importlib.util.spec_from_file_location("fidelity_fixtures_gen", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def const_block(name: str, variant: str | None, note: str, data: bytes) -> str:
    literal = repr(variant) if variant is not None else "None"
    lines = [
        f"/// {note}",
        "///",
        f"/// fixtures_gen.build_fixture(kind=\"part\", seed=0, variant={literal});",
        f"/// {len(data)} bytes.",
        "#[rustfmt::skip]",
        f"pub const {name}: &[u8] = &[",
    ]
    for off in range(0, len(data), 16):
        row = data[off : off + 16]
        cells = ", ".join(f"0x{b:02x}" for b in row)
        lines.append(f"    {cells},")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def render(gen) -> str:
    parts = [HEADER]
    for name, variant, note in SUBSET:
        data = gen.build_fixture("part", seed=0, variant=variant)
        parts.append(const_block(name, variant, note, data))
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="output path (default: the committed port/tests/fixtures/mod.rs)",
    )
    args = parser.parse_args()
    gen = load_fixtures_gen()
    text = render(gen)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text)} bytes, {len(SUBSET)} fixtures)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
